def lpole_orders() -> dict[int, int]:
    """返回每个 |n|+1 索引的极点个数 L(|n|+1)。"""
    return {order: len(residues) for order, (residues, _poles) in _COEFFICIENTS.items()}


def get_gamma_lpole_coefficients(*, max_harmonic: int) -> dict:
    """Return the L-pole residue/pole tables needed up to ``max_harmonic``.

    ``max_harmonic`` is the largest Bessel order N the caller will assemble; the
    returned tables therefore cover orders |n| = 0..N, i.e. coefficient keys 1..N+1.
    """
    if isinstance(max_harmonic, (bool, np.bool_)):
        raise ValueError("max_harmonic must be a non-negative integer")
    try:
        max_harmonic = operator.index(max_harmonic)
    except TypeError:
        raise ValueError("max_harmonic must be a non-negative integer") from None
    if max_harmonic < 0:
        raise ValueError("max_harmonic must be a non-negative integer")
    if max_harmonic + 1 > max(_COEFFICIENTS):
        raise ValueError(
            f"max_harmonic={max_harmonic} needs coefficient order {max_harmonic + 1}, "
            f"but the frozen table only reaches order {max(_COEFFICIENTS)}"
        )
    orders = list(range(1, max_harmonic + 2))
    residues = {order: np.asarray(_COEFFICIENTS[order][0], dtype=complex) for order in orders}
    poles = {order: np.asarray(_COEFFICIENTS[order][1], dtype=complex) for order in orders}
    return {
        "orders": orders,
        "order_lengths": {order: int(residues[order].size) for order in orders},
        "residues": residues,
        "poles": poles,
        "total_poles": int(sum(residues[order].size for order in orders)),
    }

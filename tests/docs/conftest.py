"""Shared documentation snapshot fixtures for the docs layer.

The documentation build is the expensive part of this layer.  Building one
canonical snapshot per session and copying it per test keeps every docs test on
the same generated bytes without rebuilding Sphinx per file.
"""

from __future__ import annotations

import shutil
from pathlib import Path
import sys

import pytest

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts"))
sys.path.insert(0, str(Path(__file__).resolve().parent))

from scirel_docs import build  # noqa: E402
from _document_fixtures import copy_example_closure  # noqa: E402


@pytest.fixture(scope="session")
def built_snapshot(tmp_path_factory):
    output = tmp_path_factory.mktemp("sphinx") / "docs"
    documents = copy_example_closure(tmp_path_factory.mktemp("reader-inputs") / "documents")
    build(documents, output)
    return output


@pytest.fixture
def snapshot(tmp_path, built_snapshot):
    return Path(shutil.copytree(built_snapshot, tmp_path / "docs"))


@pytest.fixture(scope="session")
def built_english_snapshot(tmp_path_factory):
    output = tmp_path_factory.mktemp("sphinx-en") / "docs"
    documents = copy_example_closure(tmp_path_factory.mktemp("english-inputs") / "documents")
    build(documents, output, language="en")
    return output


@pytest.fixture
def english_snapshot(tmp_path, built_english_snapshot):
    return Path(shutil.copytree(built_english_snapshot, tmp_path / "docs-en"))
